-- =====================================================================
-- 4. ROLLBACK NOTE
-- =====================================================================
--
-- BEFORE COMMIT
--   ROLLBACK; — restores everything, including FOREIGN_KEY_CHECKS, which
--   is session state and is reset when the session ends regardless.
--
-- AFTER COMMIT
--   The change is a rename, so it reverses exactly by swapping the old
--   and new ids in section 2 and re-running with the same
--   FOREIGN_KEY_CHECKS suspension. Nothing is dropped and no row is
--   deleted, so no data can be lost by reversing it. Keep the completed
--   section 2 as the reverse script.
--
--   Reverse order does not matter (parent and children move together
--   inside one transaction with checks suspended), but keep the same
--   three-statement grouping per aspect so a partial reversal is not
--   possible.
--
-- TAKE A BACKUP FIRST
--   Follow the convention used for earlier schema work (data model §21
--   records `assurly_backup_v3` for the April 2026 pass). At minimum:
--     mysqldump --single-transaction --set-gtid-purged=OFF \
--       <db> mat_aspects mat_standards user_aspect_assignments \
--       > req010_pre_migration.sql
--
-- APPLICATION IMPACT
--   Aspect ids are not persisted client-side beyond the lifetime of a
--   page, so no cache invalidation is required. Any user holding an open
--   edit dialog for a renamed aspect at the moment of the migration will
--   get a 404 on save and must reload — the window is small and the
--   failure is safe, but prefer a quiet period.
--
--   No deploy ordering constraint: the REQ-010 code change is compatible
--   with both old and new ids, so this migration can be applied before or
--   after that release.
--
